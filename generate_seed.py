"""
ArchiFlow seed data generator.

Reads materials.csv (semi-real catalogue) and generates synthetic users, clients,
suppliers, projects, supplier prices and material usage. Writes seed.sql.

Usage:
    pip install faker bcrypt
    python generate_seed.py
Then in MySQL (after running the schema file):
    source C:/path/to/seed.sql
"""
import csv
import random
from datetime import date, timedelta

import bcrypt
from faker import Faker

random.seed(42)          # same data every run, so both teammates get identical databases
Faker.seed(42)
fake = Faker("en_IN")

TODAY = date(2026, 10, 19)
DEMO_PASSWORD = "Archi@2026"   # login password for every seeded user (demo only)


def q(value):
    """Turn a Python value into a safe SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def row(*values):
    return "(" + ", ".join(q(v) for v in values) + ")"


out = []
out.append("-- Generated by generate_seed.py. Run AFTER archiflow_schema_and_queries.sql")
out.append("USE archiflow;")
out.append("SET FOREIGN_KEY_CHECKS = 0;")
for t in ["price_history", "material_usage", "supplier_materials", "materials",
          "material_categories", "suppliers", "projects", "clients", "users"]:
    out.append(f"TRUNCATE TABLE {t};")
out.append("SET FOREIGN_KEY_CHECKS = 1;\n")

# ---------------------------------------------------------------- users
pw_hash = bcrypt.hashpw(DEMO_PASSWORD.encode(), bcrypt.gensalt(rounds=10)).decode()
users = [("Admin User", "admin@archiflow.in", "ADMIN")]
for _ in range(4):
    first, last = fake.first_name(), fake.last_name()
    users.append((f"{first} {last}", f"{first.lower()}.{last.lower()}@archiflow.in", "ARCHITECT"))
out.append("INSERT INTO users (full_name, email, password_hash, role) VALUES")
out.append(",\n".join(row(n, e, pw_hash, r) for n, e, r in users) + ";\n")
architect_ids = list(range(2, len(users) + 1))

# ---------------------------------------------------------------- materials
with open("materials.csv", newline="", encoding="utf-8") as f:
    materials = list(csv.DictReader(f))

categories = list(dict.fromkeys(m["category"] for m in materials))
cat_id = {c: i + 1 for i, c in enumerate(categories)}
out.append("INSERT INTO material_categories (name) VALUES")
out.append(",\n".join(row(c) for c in categories) + ";\n")

out.append("INSERT INTO materials (category_id, name, description, unit, durability_rating, maintenance_level) VALUES")
out.append(",\n".join(
    row(cat_id[m["category"]], m["name"], m["description"], m["unit"],
        int(m["durability_rating"]), m["maintenance_level"])
    for m in materials) + ";\n")
for i, m in enumerate(materials):
    m["id"] = i + 1
    m["base_price"] = float(m["base_price"])

# ---------------------------------------------------------------- suppliers
cities = ["Bengaluru", "Kochi", "Mysuru", "Chennai", "Hyderabad", "Mumbai", "Pune", "Coimbatore"]
prefixes = ["Sri Lakshmi", "Malabar", "Deccan", "Royal", "Prime", "Southern", "Classic",
            "Shree Ganesh", "Coastal", "Urban", "Heritage", "Metro"]
suffixes = ["Building Materials", "Traders", "Tiles & Sanitary", "Hardware", "Interiors",
            "Stone Gallery", "Build Mart", "Enterprises"]
random.shuffle(prefixes)
suppliers = []
for i in range(12):
    name = f"{prefixes[i]} {random.choice(suffixes)}"
    slug = prefixes[i].lower().replace(" ", "")
    suppliers.append((name, f"sales@{slug}.in", fake.numerify("9#########"),
                      random.choice(cities), round(random.uniform(3.2, 4.9), 1)))
out.append("INSERT INTO suppliers (name, email, phone, city, rating) VALUES")
out.append(",\n".join(row(*s) for s in suppliers) + ";\n")

# ---------------------------------------------------------------- supplier_materials
offers = {}   # material_id -> list of (supplier_id, price)
lines = []
for m in materials:
    for sid in random.sample(range(1, len(suppliers) + 1), random.randint(2, 4)):
        price = round(m["base_price"] * random.uniform(0.85, 1.2), 2)
        offers.setdefault(m["id"], []).append((sid, price))
        lines.append(row(sid, m["id"], price, random.randint(2, 21)))
out.append("INSERT INTO supplier_materials (supplier_id, material_id, unit_price, lead_time_days) VALUES")
out.append(",\n".join(lines) + ";\n")

# ---------------------------------------------------------------- clients
clients = []
company_kinds = ["Hotels", "Developers", "Hospitals", "School", "Retail", "Infotech"]
for i in range(10):
    if i % 2 == 0:
        name = f"{fake.last_name()} {random.choice(company_kinds)}"
        email = f"projects@{name.split()[0].lower()}{i}.in"
    else:
        name = f"{fake.first_name()} {fake.last_name()}"
        email = f"{name.split()[0].lower()}{i}@gmail.com"
    clients.append((name, email, fake.numerify("9#########"), random.choice(cities)))
out.append("INSERT INTO clients (name, email, phone, city) VALUES")
out.append(",\n".join(row(*c) for c in clients) + ";\n")

# ---------------------------------------------------------------- projects
# (type, name pattern, description, categories this project uses)
templates = [
    ("HOSPITALITY", "{} Hotel Lobby Renovation",
     "Renovation of a busy hotel lobby and reception needing premium, hard-wearing flooring, acoustic ceilings and an elegant feature wall.",
     ["Flooring", "Ceiling", "Wall finish", "Paint"]),
    ("RESIDENTIAL", "{} Villa",
     "Two-storey family villa in a humid coastal climate; low-maintenance, moisture-resistant finishes and monsoon-proof exterior.",
     ["Flooring", "Paint", "Doors and windows", "Plumbing and sanitary", "Structural and masonry"]),
    ("INSTITUTIONAL", "{} School Classroom Block",
     "New classroom wing with high-traffic corridors, easy-to-clean surfaces, good acoustics and child-safe toilets.",
     ["Flooring", "Ceiling", "Paint", "Plumbing and sanitary", "Structural and masonry"]),
    ("COMMERCIAL", "{} Tech Park Office Floor",
     "Open-plan office fit-out with glass cabins, modular ceiling for services access and durable carpet-free flooring.",
     ["Flooring", "Ceiling", "Doors and windows", "Wall finish"]),
    ("INTERIOR", "{} Apartment Interiors",
     "Three-bedroom apartment interior with modern kitchen, wood-look bedrooms and premium bathrooms.",
     ["Flooring", "Countertops", "Plumbing and sanitary", "Paint", "Wall finish"]),
    ("COMMERCIAL", "{} Clinic Fit-out",
     "Outpatient clinic requiring hygienic, seamless, chemical-resistant surfaces and anti-microbial finishes.",
     ["Flooring", "Paint", "Countertops", "Ceiling"]),
    ("HOSPITALITY", "{} Cafe and Restaurant",
     "Rustic cafe with exposed-brick walls, warm wooden ceiling and a stainless steel commercial kitchen.",
     ["Wall finish", "Ceiling", "Countertops", "Flooring"]),
    ("RESIDENTIAL", "{} Row Houses",
     "Cluster of affordable row houses built quickly with eco-friendly masonry and budget finishes.",
     ["Structural and masonry", "Flooring", "Paint", "Doors and windows"]),
    ("COMMERCIAL", "{} Retail Showroom",
     "Ground-floor showroom with large-format tiles, bright facade cladding and frameless glass frontage.",
     ["Flooring", "Wall finish", "Doors and windows", "Ceiling"]),
    ("INSTITUTIONAL", "{} Community Auditorium",
     "Mid-size auditorium needing sound-absorbing walls and ceiling, fire-rated doors and durable aisles.",
     ["Wall finish", "Ceiling", "Doors and windows", "Flooring"]),
]
qty_range = {"sqft": (150, 2500), "sqm": (20, 200), "piece": (2, 40), "kg": (200, 4000),
             "litre": (20, 300), "rft": (50, 600), "bag": (20, 400)}
areas = {"Flooring": ["Ground floor", "Lobby", "Corridors", "Bedrooms", "Living area"],
         "Wall finish": ["Feature wall", "Reception", "Front elevation", "Bathrooms"],
         "Ceiling": ["Main hall", "Lobby ceiling", "Classrooms", "Bathrooms"],
         "Paint": ["Interior walls", "Exterior walls", "Terrace", "Railings"],
         "Countertops": ["Kitchen", "Vanity", "Reception desk", "Pantry"],
         "Doors and windows": ["Main entrance", "Bedrooms", "Facade", "Stairwell"],
         "Plumbing and sanitary": ["Toilets", "Kitchen", "Terrace", "Bathrooms"],
         "Structural and masonry": ["Superstructure", "Partition walls", "Slab", "Basement"]}

statuses = ["COMPLETED", "COMPLETED", "IN_PROGRESS", "IN_PROGRESS", "IN_PROGRESS",
            "IN_PROGRESS", "ON_HOLD", "COMPLETED", "IN_PROGRESS", "PLANNING"]
projects = []
for i, (ptype, pattern, desc, cats) in enumerate(templates):
    start = TODAY - timedelta(days=random.randint(60, 600))
    status = statuses[i]
    end = start + timedelta(days=random.randint(120, 300)) if status == "COMPLETED" else None
    if end and end > TODAY:
        end = TODAY - timedelta(days=random.randint(5, 40))
    budget = random.randrange(1_500_000, 12_000_000, 50_000)
    projects.append(dict(id=i + 1, client=i + 1, architect=random.choice(architect_ids),
                         name=pattern.format(fake.last_name()), desc=desc, type=ptype,
                         location=random.choice(cities), area=random.randrange(1500, 20000, 100),
                         status=status, budget=budget, start=start, end=end, cats=cats))
out.append("INSERT INTO projects (client_id, lead_architect_id, name, description, project_type, "
           "location, area_sqft, status, budget, start_date, end_date) VALUES")
out.append(",\n".join(
    row(p["client"], p["architect"], p["name"], p["desc"], p["type"], p["location"], p["area"],
        p["status"], p["budget"], p["start"].isoformat(), p["end"].isoformat() if p["end"] else None)
    for p in projects) + ";\n")

# ---------------------------------------------------------------- material usage
# Inserted through the stored procedure, so the transaction and budget trigger run on every row.
out.append("-- Usage recorded through the transactional procedure")
for p in projects:
    if p["status"] == "PLANNING":
        continue                                   # no purchases yet
    pool = [m for m in materials if m["category"] in p["cats"]]
    spent, cap = 0.0, p["budget"] * random.uniform(0.55, 0.9)
    last_day = p["end"] or TODAY
    for _ in range(random.randint(12, 24)):
        m = random.choice(pool)
        sid, price = random.choice(offers[m["id"]])
        lo, hi = qty_range[m["unit"]]
        qty = random.randint(lo, hi)
        cost = qty * price
        if spent + cost > cap:
            continue                               # keep every project within budget
        spent += cost
        used_on = p["start"] + timedelta(days=random.randint(0, max(1, (last_day - p["start"]).days)))
        out.append("CALL record_material_usage" +
                   row(p["id"], sid, m["id"], p["architect"], qty,
                       random.choice(areas[m["category"]]), used_on.isoformat()) + ";")

# ---------------------------------------------------------------- price changes (fills price_history)
out.append("\n-- Supplier price revisions (the trigger logs each one into price_history)")
for m in random.sample(materials, 15):
    sid, price = random.choice(offers[m["id"]])
    new_price = round(price * random.uniform(0.92, 1.15), 2)
    out.append(f"UPDATE supplier_materials SET unit_price = {new_price} "
               f"WHERE supplier_id = {sid} AND material_id = {m['id']};")

out.append("\nSELECT 'Seed complete' AS status;")
with open("seed.sql", "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("Wrote seed.sql")
